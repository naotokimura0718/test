CHECK_STRUCTURAL_USER = """\
以下は{project_name}の設計図面です。あなたのベテラン経験を活かして、
施工時に成立するかどうかを厳しくチェックしてください。

特にサッシ回りの構造的成立性に注意を払ってください。
"""


def make_user_prompt(project_name: str) -> str:
    """User promptを生成する。"""
    return CHECK_STRUCTURAL_USER.format(project_name=project_name)
